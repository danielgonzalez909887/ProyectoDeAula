    private void listarHuespedes() {
        try {
            IGetAllHuespedQuery query = new GetAllHuespedQueryHandler();
            huespedesList = query.handler();

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            // formateador para la fecha de nacimiento
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

            for (Huesped h : huespedesList) {
                String fecha = h.getFechaNacimientoHuesped() != null
                    ? sdf.format(h.getFechaNacimientoHuesped())
                    : "N/A";

                model.addRow(new Object[]{
                    h.getNombresHuesped(),
                    h.getApellidosHuesped(),
                    h.getIdentificacionHuespedAcompa(),
                    fecha,
                    h.getGeneroHuesped() != null 
                        ? h.getGeneroHuesped() 
                        : "N/A",
                    h.getEmailHuesped() != null 
                        ? h.getEmailHuesped() 
                        : "N/A"
                });
            }

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(
                this,
                "Error al listar huéspedes: " + ex.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }


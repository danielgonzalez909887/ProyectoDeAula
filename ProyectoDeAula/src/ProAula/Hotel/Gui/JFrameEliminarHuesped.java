    private void jButtonEditarHuespedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditarHuespedActionPerformed
        int fila = jTable1.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
                "Seleccione un huésped para editar.",
                "Atención",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        Huesped h = huespedesList.get(fila);

        JFrameEditarHuesped ventanaEditar = new JFrameEditarHuesped();

        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String fechaStr = h.getFechaNacimientoHuesped() != null
            ? sdf.format(h.getFechaNacimientoHuesped())
            : "";

        ventanaEditar.setDatosHuesped(
            h.getNombresHuesped(),
            h.getApellidosHuesped(),
            h.getIdentificacionHuespedAcompa(),
            fechaStr,
            h.getGeneroHuesped() != null ? h.getGeneroHuesped() : "",
            h.getEmailHuesped()  != null ? h.getEmailHuesped()  : ""
        );
        ventanaEditar.setHuespedId(h.getId());
        
        ventanaEditar.setLocationRelativeTo(this);
        ventanaEditar.setVisible(true);
    }//GEN-LAST:event_jButtonEditarHuespedActionPerformed

    private void jButtonEliminarHuespedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEliminarHuespedActionPerformed
        try {
            int fila = jTable1.getSelectedRow();
            if (fila == -1) {
                JOptionPane.showMessageDialog(
                    this,
                    "Seleccione un huésped para eliminar.",
                    "Atención",
                    JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            int confirm = JOptionPane.showConfirmDialog(
                this,
                "¿Estás seguro de que deseas eliminar este huésped?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION
            );
            if (confirm != JOptionPane.YES_OPTION) {
                return;
            }

            Huesped h = huespedesList.get(fila);
            DeleteHuespedCommand command = new DeleteHuespedCommand(h.getId());
            IDeleteHuespedCommand handler = new DeleteHuespedCommandHandler();
            Huesped eliminado = handler.handler(command);

            JOptionPane.showMessageDialog(
                this,
                "Huésped eliminado correctamente:\n" +
                eliminado.getNombresHuesped() + " " + eliminado.getApellidosHuesped(),
                "Éxito",
                JOptionPane.INFORMATION_MESSAGE
            );
            listarHuespedes();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(
                this,
                "Error al eliminar el huésped: " + ex.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_jButtonEliminarHuespedActionPerformed


    private List<Habitaciones> habitacionesList = new ArrayList<>();
    
    private void listarHabitaciones() {
        try {
            GetAllHabitacionesQueryHandler handler = new GetAllHabitacionesQueryHandler();
            habitacionesList = handler.handler();

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            for (Habitaciones h : habitacionesList) {
                model.addRow(new Object[]{
                    h.getNumeroHabitacion(),
                    h.getEstadoHabitacion(),
                    h.getIdentificacionHuesped() != null
                        ? h.getIdentificacionHuesped()
                        : "N/A"
                });
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this,
                "Error al listar habitaciones: " + ex.getMessage());
        }
    }
    


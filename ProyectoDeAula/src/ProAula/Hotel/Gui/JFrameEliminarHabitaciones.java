    private void jButtonEditarHabitacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditarHabitacionActionPerformed
        int fila = jTable1.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione una habitación para editar.");
            return;
        }
        Habitaciones hab = habitacionesList.get(fila);
        JFrameEditarHabitacion ventanaEditar = new JFrameEditarHabitacion();
        ventanaEditar.setDatosHabitacion(
            String.valueOf(hab.getNumeroHabitacion()),
            hab.getEstadoHabitacion(),
            hab.getIdentificacionHuesped()
        );
        ventanaEditar.setHabitacionId(hab.getId());
        ventanaEditar.setLocationRelativeTo(this);
        ventanaEditar.setVisible(true);
    }//GEN-LAST:event_jButtonEditarHabitacionActionPerformed

    private void jButtonEliminarHabitacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEliminarHabitacionActionPerformed
        try {
            int fila = jTable1.getSelectedRow();
            if (fila == -1) {
                JOptionPane.showMessageDialog(this, "Seleccione una habitación para eliminar.");
                return;
            }

            int confirm = JOptionPane.showConfirmDialog(
                this,
                "¿Estás seguro de que deseas eliminar esta habitación?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION
            );
            if (confirm != JOptionPane.YES_OPTION) {
                return;
            }

            Habitaciones h = habitacionesList.get(fila);
            DeleteHabitacionCommand command = new DeleteHabitacionCommand(h.getId());
            IDeleteHabitacionCommand handler = new DeleteHabitacionCommandHandler();
            handler.handler(command);

            JOptionPane.showMessageDialog(this, "Habitación eliminada correctamente.");
            listarHabitaciones();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al eliminar la habitación: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonEliminarHabitacionActionPerformed

